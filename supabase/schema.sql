-- EmpHRMS schema for Supabase (Postgres).
-- Run in: Supabase dashboard -> SQL Editor -> New query -> paste -> Run.

-- ---------------------------------------------------------------------------
-- logins: admin credentials (password is a bcrypt hash, never plain text)
-- ---------------------------------------------------------------------------
create table public.logins (
  id            bigint generated by default as identity primary key,
  user_id       text not null unique,
  password_hash text not null
);

-- ---------------------------------------------------------------------------
-- employees: basic employee details
-- ---------------------------------------------------------------------------
create type public.employee_status as enum ('ACTIVE', 'ON_LEAVE', 'INACTIVE');

create table public.employees (
  id              bigint generated by default as identity primary key,
  employee_code   text not null unique,
  first_name      text not null,
  last_name       text not null,
  email           text not null unique,
  phone           text,
  department      text,
  designation     text,
  date_of_joining date,
  status          public.employee_status not null default 'ACTIVE'
);

create index employees_department_idx on public.employees (department);
create index employees_status_idx on public.employees (status);

-- ---------------------------------------------------------------------------
-- attendance: one row per day, holding the ids of employees who were present
-- and absent. Employees in neither list are "not marked". Ids are not foreign
-- keys, so a deleted employee's id can linger in old days (the app ignores it).
-- ---------------------------------------------------------------------------
create table public.attendance (
  date        date primary key,
  present_ids bigint[] not null default '{}',
  absent_ids  bigint[] not null default '{}'
);

-- ---------------------------------------------------------------------------
-- salaries: one record per employee per month. `month` is always the 1st.
-- ---------------------------------------------------------------------------
create table public.salaries (
  id          bigint generated by default as identity primary key,
  employee_id bigint not null references public.employees (id) on delete cascade,
  month       date not null,
  basic       numeric(12, 2) not null,
  allowances  numeric(12, 2) not null default 0,
  deductions  numeric(12, 2) not null default 0,
  net_pay     numeric(12, 2) not null,
  constraint salaries_employee_month_key unique (employee_id, month)
);

-- ---------------------------------------------------------------------------
-- Row Level Security
-- Enabled with no policies: the public anon/authenticated keys cannot read or
-- write these tables. Only server code using a direct Postgres connection (as
-- Prisma does here) or the service_role key can access them. Never expose the
-- service_role key to the browser.
-- ---------------------------------------------------------------------------
alter table public.logins enable row level security;
alter table public.employees enable row level security;
alter table public.attendance enable row level security;
alter table public.salaries enable row level security;
